import { marked, Renderer, type Token, type Tokens } from "marked";

const MAX_TELEGRAM_TEXT_LENGTH = 4096;

type TelegramChunk = { html: string; text: string };
type OpenTag = { name: string; opening: string; closing: string };

function escapeHtml(value: string): string {
	return value.replace(/[&<>"']/g, character => {
		switch (character) {
			case "&": return "&amp;";
			case "<": return "&lt;";
			case ">": return "&gt;";
			case '"': return "&quot;";
			default: return "&#39;";
		}
	});
}

function safeHref(value: string): string | undefined {
	const href = value.trim();
	if (!href || /[\u0000-\u0020\u007f]/.test(href)) return undefined;
	try {
		const protocol = new URL(href).protocol.toLowerCase();
		return ["http:", "https:", "mailto:", "tg:"].includes(protocol) ? href : undefined;
	} catch {
		return undefined;
	}
}

function makeRenderer(): Renderer {
	const renderer = new Renderer();
	let listDepth = 0;

	renderer.heading = function ({ tokens }: Tokens.Heading): string {
		return `<b>${this.parser.parseInline(tokens)}</b>\n`;
	};
	renderer.paragraph = function ({ tokens }: Tokens.Paragraph): string {
		return `${this.parser.parseInline(tokens)}\n\n`;
	};
	renderer.br = (): string => "\n";
	renderer.html = ({ text }: Tokens.HTML | Tokens.Tag): string => escapeHtml(text);
	// Markdown text is always escaped, including entity-looking input, so only
	// the tags generated by this renderer reach Telegram's HTML parser.
	renderer.text = function (token: Tokens.Text | Tokens.Escape): string {
		return "tokens" in token && token.tokens
			? this.parser.parseInline(token.tokens)
			: escapeHtml(token.text);
	};
	renderer.link = function ({ href, tokens }: Tokens.Link): string {
		const label = this.parser.parseInline(tokens);
		const safe = safeHref(href);
		return safe ? `<a href="${escapeHtml(safe)}">${label}</a>` : label;
	};
	renderer.image = function ({ href, text, tokens }: Tokens.Image): string {
		const label = tokens.length ? this.parser.parseInline(tokens) : escapeHtml(text);
		const safe = safeHref(href);
		return safe ? `<a href="${escapeHtml(safe)}">${label || "Image"}</a>` : label || "Image";
	};
	renderer.list = function (token: Tokens.List): string {
		const depth = listDepth++;
		const renderItemTokens = (tokens: Token[]): string => tokens.map(child => {
			switch (child.type) {
				case "text":
				case "paragraph":
					return this.parser.parseInline(child.tokens ?? [{ type: "text", raw: child.text, text: child.text }]);
				case "list":
					return `\n${this.list(child as Tokens.List)}`;
				case "blockquote":
					return this.blockquote(child as Tokens.Blockquote);
				case "code":
					return this.code(child as Tokens.Code);
				case "table":
					return this.table(child as Tokens.Table);
				case "hr":
					return this.hr(child as Tokens.Hr);
				case "space":
					return "\n";
				default:
					return this.parser.parseInline([child]);
			}
		}).join("");
		try {
			return token.items.map((item, index) => {
				const body = renderItemTokens(item.tokens).trim();
				const marker = item.task
					? (item.checked ? "☑" : "☐")
					: token.ordered ? `${Number(token.start || 1) + index}.` : "•";
				return `${"  ".repeat(depth)}${marker} ${body}\n`;
			}).join("") + "\n";
		} finally {
			listDepth--;
		}
	};
	renderer.hr = (): string => "──────────\n";
	renderer.table = function (token: Tokens.Table): string {
		const header = token.header.map(cell => `<b>${this.parser.parseInline(cell.tokens)}</b>`).join(" | ");
		const rows = token.rows.map(row => row.map(cell => this.parser.parseInline(cell.tokens)).join(" | "));
		return [header, ...rows].join("\n") + "\n\n";
	};

	return renderer;
}

function decodeEntity(entity: string): string {
	return ({ "&amp;": "&", "&lt;": "<", "&gt;": ">", "&quot;": '"', "&#39;": "'" })[entity.toLowerCase()] ?? entity;
}

const HTML_TOKEN = /<\/?[a-z][a-z0-9]*(?:\s[^<>]*?)?\s*\/?>|&(?:amp|lt|gt|quot|#39);|[\s\S]/giu;

/** Split renderer-produced Telegram HTML without cutting entities or leaving tags unbalanced. */
export function chunkTelegramHtml(html: string, maxLength = MAX_TELEGRAM_TEXT_LENGTH): TelegramChunk[] {
	if (!Number.isSafeInteger(maxLength) || maxLength < 1) throw new Error("Invalid Telegram message length");
	const chunks: TelegramChunk[] = [];
	const stack: OpenTag[] = [];
	let currentHtml = "";
	let currentText = "";
	let visibleLength = 0;

	const flush = (): void => {
		if (!currentText) return;
		for (let index = stack.length - 1; index >= 0; index--) currentHtml += stack[index].closing;
		chunks.push({ html: currentHtml, text: currentText });
		currentHtml = stack.map(tag => tag.opening).join("");
		currentText = "";
		visibleLength = 0;
	};

	for (const [raw] of html.matchAll(HTML_TOKEN)) {
		if (raw.startsWith("<")) {
			const name = /^<\/?([a-z][a-z0-9]*)/i.exec(raw)![1].toLowerCase();
			const closing = raw.startsWith("</");
			currentHtml += raw;
			if (name !== "br" && !raw.endsWith("/>")) {
				if (closing) stack.pop();
				else {
					stack.push({ name, opening: raw, closing: `</${name}>` });
				}
			}
			continue;
		}

		const visible = raw.startsWith("&") ? decodeEntity(raw) : raw;
		if (visibleLength + visible.length > maxLength) flush();
		currentHtml += raw;
		currentText += visible;
		visibleLength += visible.length;
	}
	flush();
	return chunks;
}

/** Convert Markdown into Telegram's supported HTML subset and split it safely. */
export function renderTelegramMarkdown(markdown: string, maxLength = MAX_TELEGRAM_TEXT_LENGTH): TelegramChunk[] {
	const html = marked.parse(markdown, {
		async: false,
		gfm: true,
		renderer: makeRenderer(),
	});
	if (typeof html !== "string") throw new Error("Markdown rendering unexpectedly returned a promise");
	return chunkTelegramHtml(html, maxLength);
}
